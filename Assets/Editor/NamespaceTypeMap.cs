        internal static Type Resolve(string ns, string name, string assembly)
        {
            var fullName = string.IsNullOrEmpty(ns) ? name : ns + "." + name;
            if (assembly == "Assembly-CSharp" && Names.TryGetValue(fullName, out var current))
                fullName = current;
            return Type.GetType(fullName + ", " + assembly, false);
        }

        internal static bool IsMechanismNamespace(string ns) =>
